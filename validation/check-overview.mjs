import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[],report={};
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8768');
 await page.waitForFunction(()=>window.__atlas?.ready&&__atlas.data.frame,null,{timeout:60000});
 await page.waitForTimeout(4000);
 await page.screenshot({path:'validation/earth-current.png'});
 const original=await page.evaluate(()=>({position:[...__atlas.state.position],frames:__atlas.metrics.frames}));
 await page.click('#system-map-open');
 await page.waitForFunction(()=>__atlas.map?.move);
 await page.waitForTimeout(300);
 const inTransit=await page.evaluate(()=>({position:__atlas.state.position,frames:__atlas.metrics.frames}));
 assert.notDeepEqual(inTransit.position,original.position,'Map actually moves the camera');
 assert.ok(inTransit.frames>original.frames,'The live universe keeps drawing during the maneuver');
 await page.waitForFunction(()=>__atlas.map&&!__atlas.map.move);
 await page.screenshot({path:'validation/system-overview.png'});
 report.overview=await page.evaluate(()=>({position:__atlas.state.position,nodes:document.querySelectorAll('#map-svg .map-node').length,frames:__atlas.metrics.frames}));
 assert.ok(report.overview.nodes>=9);
 await page.locator('#map-svg [data-world="saturn"] .node-hit').click();
 assert.equal(await page.locator('#map-selected-name').innerText(),'Saturn');
 assert.equal(await page.evaluate(()=>__atlas.selected.id),'earth','Selection previews before starting a flight');
 await page.click('#map-fly');
 await page.waitForFunction(()=>!__atlas.travel&&__atlas.selected.id==='saturn',null,{timeout:25000});
 assert.equal(await page.evaluate(()=>!!__atlas.map),false);
 const saturnCamera=await page.evaluate(()=>({...__atlas.state,position:[...__atlas.state.position]}));
 await page.click('#system-map-open');
 await page.waitForFunction(()=>__atlas.map&&!__atlas.map.move);
 await page.getByRole('button',{name:'Earth + moons',exact:true}).click();
 await page.waitForFunction(()=>__atlas.map&&!__atlas.map.move);
 await page.screenshot({path:'validation/moon-overview.png'});
 assert.equal(await page.locator('#map-svg [data-world="earth"]').count(),1);
 assert.equal(await page.locator('#map-svg [data-world="moon"]').count(),1);
 await page.click('#map-close');
 await page.waitForFunction(()=>!__atlas.map);
 assert.deepEqual(await page.evaluate(()=>__atlas.state.position),saturnCamera.position);
 assert.equal(await page.evaluate(()=>__atlas.mode),'orbit');
 // Verify rolled-camera movement, then allow adaptive rendering to settle.
 await page.evaluate(()=>__atlas.returnEarth({instant:true}));
 await page.waitForTimeout(1000);
 await page.locator('#mode-toggle').click();
 const before=await page.evaluate(()=>({...__atlas.state,position:[...__atlas.state.position]}));
 await page.locator('#viewport').focus();await page.keyboard.down('KeyD');await page.waitForTimeout(350);await page.keyboard.up('KeyD');
 const after=await page.evaluate(()=>__atlas.state.position);
 const r=[-Math.cos(before.yaw),0,Math.sin(before.yaw)],f=[Math.sin(before.yaw)*Math.cos(before.pitch),Math.sin(before.pitch),Math.cos(before.yaw)*Math.cos(before.pitch)];
 const u=[r[1]*f[2]-r[2]*f[1],r[2]*f[0]-r[0]*f[2],r[0]*f[1]-r[1]*f[0]];
 const right=r.map((v,i)=>v*Math.cos(before.roll)+u[i]*Math.sin(before.roll));
 assert.ok(after.reduce((sum,v,i)=>sum+(v-before.position[i])*right[i],0)>0,'D strafes to screen right with Earth north up');
 await page.evaluate(()=>__atlas.returnEarth({instant:true}));await page.waitForTimeout(4000);
 await page.locator('#viewport').focus();await page.keyboard.down('ArrowRight');await page.waitForTimeout(3000);await page.keyboard.up('ArrowRight');
 report.movingEarth=await page.evaluate(()=>{const a=__atlas,mean=x=>x.reduce((s,v)=>s+v,0)/x.length,quant=(x,q)=>[...x].sort((a,b)=>a-b)[Math.floor((x.length-1)*q)];return {cols:a.state.cols,rows:a.state.rows,fps:1000/mean(a.metrics.frameIntervals.slice(-120)),medianWorkerMs:quant(a.metrics.computeTimes.slice(-120),.5),p95WorkerMs:quant(a.metrics.computeTimes.slice(-120),.95),heapBytes:a.data.stats.heap_bytes};});
 await page.setViewportSize({width:390,height:844});await page.click('#system-map-open');
 await page.waitForFunction(()=>__atlas.map&&!__atlas.map.move);
 await page.getByRole('button',{name:'Earth + moons',exact:true}).click();
 await page.waitForFunction(()=>__atlas.map&&!__atlas.map.move);
 await page.locator('#map-svg [data-world="moon"] .node-hit').click();
 assert.equal(await page.locator('#map-selected-name').innerText(),'Moon');
 await page.screenshot({path:'validation/mobile-moon-map.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.click('#map-close');await page.waitForFunction(()=>!__atlas.map);
 assert.deepEqual(errors,[]);report.passed=true;report.errors=errors;
 console.log(JSON.stringify(report,null,2));
} finally {await browser.close();await writeFile('validation/overview-result.json',JSON.stringify(report,null,2)+'\n');}
